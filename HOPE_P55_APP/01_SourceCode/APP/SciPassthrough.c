void	sSciPassthrough(INT8U device, INT8U rx_sciid, INT8U tx_sciid)
{
	INT8U	RxLen;
	INT8U	*RxBuff;
	INT8U	*TxBuff;
	INT8U	i = 0;

	RxLen = bGetSciRxLen(rx_sciid);
	RxBuff = pbGetSciRxBuff(rx_sciid);
	TxBuff = pbGetSciTxBuff(rx_sciid);

	if(device == SCI_PASSTHROUGH_INV)
	{
		if(RxBuff[cMODBUS_ADDR] != cMODBUS_ADDR_PASS_INV)
		{
			return;
		}
	}
	else if(device == SCI_PASSTHROUGH_MPPT)
	{
		if(RxBuff[cMODBUS_ADDR] != cMODBUS_ADDR_PASS_MPPT)
		{
			//return;
		}
	}
	else
	{
		return;
	}

	for(i = 0; i < RxLen; i++)
	{
		TxBuff[i] = RxBuff[i];
	}

	if(sSciGetTxStatus(tx_sciid) != cSciTxBusy)
	{
		sSciWrite(tx_sciid, TxBuff, RxLen);
	}

	swSetPassthroughDelay(0);
}

