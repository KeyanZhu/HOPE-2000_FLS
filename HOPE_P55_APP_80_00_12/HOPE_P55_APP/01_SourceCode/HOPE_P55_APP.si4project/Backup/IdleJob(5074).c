INT16U sIdleCount = 0;

/********************************************************************************
* Routines' implementations														*
********************************************************************************/
void	sIdleJob(void)
{
	INT16U	wEvent;
	
	sIdleJobInit();
	
	while(1)
	{
		wEvent = OSEventPend();

		if(wEvent & (1 << eIdleTimer))
		{
			sIdleCount++;
			if(sIdleCount <= cT500ms)
			{	
				mLED1On;
				mLED2On;
				mLED3On;	// Run Led
				mLED4On;
			}
			else if(sIdleCount <= cT1sec)
			{
				mLED1Off;
				mLED2Off;
				mLED3Off;
				mLED4Off;
			}
			else 
			{
				sIdleCount = 0;
			}	
		}
	}
}

void	sIdleJobInit(void)
{
	OSMaskEventPend(1 << eIdleTimer);
}


